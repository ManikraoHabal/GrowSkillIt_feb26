package day1;

public class Program1_ASCII {
	
	public static void main(String[] args)
	{
		char value='A';
		int data=value;
		System.out.println(data);
		
		char alpha='a';
		int val=alpha;
		System.out.println(val);
		
		char alpha1=' ';
		int val2=alpha1;
		System.out.println(val2);
			
		char key='P';
		char key1='p';
		int v1=key;
		int v2=key1;
		System.out.println("ASCII: "+v1*v2);
		
		
	}
		
}
