package day1;

public class Program3_DataType {

	public static void main(String[] args) {
		
		//int takes 4 bytes
		int num=1234;
		
		System.out.println(num);
		
		//boolean takes 1 bit
		boolean state=false;
		System.out.println(state);
		
		byte ans=-128;
		System.out.println(ans);
		
		//short takes 2 bytes
		short data=-32000;
		System.out.println(data);
		
		//char takes 2 bytes
		char letter='A';
		System.out.println(letter);
		
		//long take 8 bytes
		long phno=7411509597l;
		System.out.println(phno);
		
		//float takes 4 bytes
		float marks=9.123456788f;
		System.out.println(marks);
		
		float marks1=91.2345678f;
		System.out.println(marks1);
		
		float marks3=912.345678f;
		System.out.println(marks3);
		
		
		double data1=9.1234567890123456;
		System.out.println(data1);
		
	}

}
